import json
from datetime import timedelta

from odoo import fields, http
from odoo.exceptions import LockError, ValidationError
from odoo.http import request

from odoo.addons.payment import utils as payment_utils
from odoo.addons.payment.logging import get_payment_logger
from odoo.addons.payment_orkestapay import const
from odoo.addons.payment_orkestapay.utils import (
    OrkestaPayApiError,
    WebhookVerificationError,
    verify_svix_signature,
)


_logger = get_payment_logger(__name__, sensitive_keys=const.SENSITIVE_KEYS)


class OrkestaPayController(http.Controller):

    # === BUYER RETURN === #

    @http.route(const.PAYMENT_RETURN_ROUTE, type='http', methods=['GET'], auth='public')
    def orkestapay_return(self, reference=None, access_token=None, **_kwargs):
        """Verify the payment against the API after the buyer completes the checkout.

        The URL parameters are only used to find the transaction: its state is set from the data
        queried to the API.

        :param str reference: The transaction reference.
        :param str access_token: The access token proving the URL was generated by Odoo.
        :return: A redirection to the payment status page.
        """
        tx_sudo = self._orkestapay_get_tx_from_return(reference, access_token)
        if tx_sudo:
            self._orkestapay_run_processing(
                tx_sudo, tx_sudo._orkestapay_process_from_api, 'return'
            )
        return request.redirect('/payment/status')

    @http.route(const.PAYMENT_CANCEL_ROUTE, type='http', methods=['GET'], auth='public')
    def orkestapay_cancel(self, reference=None, access_token=None, **_kwargs):
        """Cancel the OrkestaPay order and the transaction after the buyer cancels the checkout.

        The cart is left untouched so the buyer can choose another payment method.

        :param str reference: The transaction reference.
        :param str access_token: The access token proving the URL was generated by Odoo.
        :return: A redirection to the payment status page.
        """
        tx_sudo = self._orkestapay_get_tx_from_return(reference, access_token)
        if tx_sudo:
            self._orkestapay_run_processing(tx_sudo, tx_sudo._orkestapay_cancel_from_buyer)
        return request.redirect('/payment/status')

    @staticmethod
    def _orkestapay_get_tx_from_return(reference, access_token):
        """Return the transaction matching a return URL, or an empty recordset.

        :param str reference: The transaction reference.
        :param str access_token: The access token of the return URL.
        :return: The sudoed transaction, if found and authentic.
        :rtype: payment.transaction
        """
        tx_model_sudo = request.env['payment.transaction'].sudo()
        if not reference or not access_token:
            _logger.info("Received an OrkestaPay return without reference or access token.")
            return tx_model_sudo
        if not payment_utils.check_access_token(access_token, reference):
            # The reference is unauthenticated input: truncate and repr it to keep logs clean.
            _logger.warning(
                "Received an OrkestaPay return with an invalid access token for reference %r.",
                reference[:64],
            )
            return tx_model_sudo
        tx_sudo = tx_model_sudo.search(
            [('reference', '=', reference), ('provider_code', '=', 'orkestapay')], limit=1
        )
        if not tx_sudo.provider_reference:
            _logger.info("No OrkestaPay order to verify for reference %s.", reference)
            return tx_model_sudo
        return tx_sudo

    @staticmethod
    def _orkestapay_run_processing(tx_sudo, method, *args):
        """Run a processing method of the transaction in a savepoint, absorbing expected errors.

        :param payment.transaction tx_sudo: The sudoed transaction.
        :param callable method: The processing method to call.
        :return: None
        """
        try:
            with request.env.cr.savepoint():
                method(*args)
        except LockError:
            # Another request (e.g., the webhook) is processing the transaction; the status page
            # polls until it is done.
            _logger.info(
                "Transaction %s is being processed by another request.", tx_sudo.reference
            )
        except ValidationError:
            _logger.warning(
                "Could not verify the OrkestaPay payment of transaction %s; the reconciliation"
                " will retry.", tx_sudo.reference,
            )

    # === WEBHOOK === #

    @http.route(
        const.WEBHOOK_ROUTE, type='http', methods=['POST'], auth='public', csrf=False,
        save_session=False,
    )
    def orkestapay_webhook(self):
        """Process an OrkestaPay webhook.

        The Svix signature is mandatory. The body is only used to find the transaction, whose state
        is then queried to the API.

        :return: HTTP 200 when processed or deliberately ignored, 401 when the signature is
                 invalid, 500 when the payment could not be verified, so that OrkestaPay retries.
        """
        raw_body = request.httprequest.get_data()
        headers = request.httprequest.headers
        # Header and body values are logged with %r to keep log lines intact.
        message_id = (headers.get('svix-id') or headers.get('webhook-id') or '')[:64]

        providers_sudo = self._orkestapay_get_verifying_providers(raw_body, headers)
        if not providers_sudo:
            return self._orkestapay_webhook_response(401)

        try:
            event = json.loads(raw_body)
        except ValueError:
            _logger.warning("Ignored OrkestaPay webhook %r with a non-JSON body.", message_id)
            return self._orkestapay_webhook_response(200)
        if not isinstance(event, dict):
            _logger.warning("Ignored OrkestaPay webhook %r with an unexpected body.", message_id)
            return self._orkestapay_webhook_response(200)

        event_type = event.get('event_type')
        if event_type not in const.HANDLED_WEBHOOK_EVENTS:
            _logger.info("Ignored OrkestaPay webhook %r of type %r.", message_id, event_type)
            return self._orkestapay_webhook_response(200)

        payment = (event.get('data') or {}).get('payment') or {}
        reference = payment.get('merchant_order_id')
        tx_sudo = request.env['payment.transaction'].sudo().search([
            ('reference', '=', reference),
            ('provider_code', '=', 'orkestapay'),
            ('provider_id', 'in', providers_sudo.ids),
        ], limit=1) if reference else request.env['payment.transaction']
        if not tx_sudo:
            _logger.info(
                "Ignored OrkestaPay webhook %r (%r): unknown reference %r.",
                message_id, event_type, reference,
            )
            return self._orkestapay_webhook_response(200)
        if not tx_sudo.provider_reference:
            _logger.info(
                "Ignored OrkestaPay webhook %r: transaction %s has no OrkestaPay order.",
                message_id, tx_sudo.reference,
            )
            return self._orkestapay_webhook_response(200)
        if payment.get('order_id') and payment['order_id'] != tx_sudo.provider_reference:
            _logger.warning(
                "Ignored OrkestaPay webhook %r: order %r does not match transaction %s.",
                message_id, payment['order_id'], tx_sudo.reference,
            )
            return self._orkestapay_webhook_response(200)

        _logger.info(
            "Processing OrkestaPay webhook %r (%s) for transaction %s.",
            message_id, event_type, tx_sudo.reference,
        )
        is_refund_event = event_type == const.REFUND_WEBHOOK_EVENT
        try:
            with request.env.cr.savepoint():
                if is_refund_event:
                    tx_sudo._orkestapay_process_refund_event()
                else:
                    tx_sudo._orkestapay_process_from_api('webhook')
        except LockError:
            _logger.info(
                "Transaction %s is being processed by another request; OrkestaPay will retry"
                " webhook %r.", tx_sudo.reference, message_id,
            )
            return self._orkestapay_webhook_response(500)
        except OrkestaPayApiError:
            _logger.warning(
                "Could not verify the payment of transaction %s; OrkestaPay will retry webhook"
                " %r.", tx_sudo.reference, message_id,
            )
            return self._orkestapay_webhook_response(500)
        except ValidationError:
            _logger.exception(
                "Could not process OrkestaPay webhook %r for transaction %s.",
                message_id, tx_sudo.reference,
            )
            return self._orkestapay_webhook_response(200)

        if not is_refund_event and not tx_sudo.is_post_processed:
            # Without a buyer on the status page, the post-processing (e.g., the confirmation of
            # the sales order) is done by the cron, every 10 minutes. Run it sooner, but not right
            # away: the webhook usually arrives just before the buyer, whose status page then
            # post-processes the transaction; running both at once makes one of them fail.
            post_processing_cron = request.env.ref(
                'payment.cron_post_process_payment_tx', raise_if_not_found=False
            )
            already_scheduled = post_processing_cron and request.env['ir.cron.trigger'].sudo(
            ).search_count([
                ('cron_id', '=', post_processing_cron.id),
                ('call_at', '>', fields.Datetime.now()),
            ], limit=1)
            if post_processing_cron and not already_scheduled:
                post_processing_cron.sudo()._trigger(
                    at=fields.Datetime.now() + timedelta(seconds=const.POST_PROCESSING_DELAY)
                )
        return self._orkestapay_webhook_response(200)

    @staticmethod
    def _orkestapay_get_verifying_providers(raw_body, headers):
        """Return the OrkestaPay providers whose signing secret validates the webhook signature.

        :param bytes raw_body: The raw request body.
        :param headers: The request headers.
        :return: The sudoed providers whose secret matches; empty if the signature is invalid.
        :rtype: payment.provider
        """
        providers_sudo = request.env['payment.provider'].sudo().search([
            ('code', '=', 'orkestapay'), ('orkestapay_webhook_secret', '!=', False),
        ])
        verified_providers_sudo = request.env['payment.provider'].sudo()
        failure_reason = "no provider with a signing secret"
        for provider_sudo in providers_sudo:
            try:
                verify_svix_signature(provider_sudo.orkestapay_webhook_secret, headers, raw_body)
            except WebhookVerificationError as error:
                failure_reason = str(error)
            else:
                verified_providers_sudo |= provider_sudo
        if not verified_providers_sudo:
            _logger.warning(
                "Rejected an OrkestaPay webhook with an invalid signature (%s); check the Webhook"
                " Signing Secret of the provider.", failure_reason,
            )
        return verified_providers_sudo

    @staticmethod
    def _orkestapay_webhook_response(status):
        """Return an empty JSON acknowledgement with the given HTTP status."""
        return request.make_json_response({}, status=status)
